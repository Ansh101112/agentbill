// Refreshes the bundled offline price snapshot from OpenRouter's public model list.
// Usage: node scripts/snapshot-prices.ts
import { writeFileSync } from 'node:fs';
import { fetchOpenRouterPrices } from '../src/pricing.ts';

const prices = await fetchOpenRouterPrices();
const keep = /^(anthropic|openai|deepseek|z-ai|moonshotai|qwen|google|mistralai|x-ai|meta-llama|minimax)\//;
const picked = Object.fromEntries(Object.entries(prices).filter(([id]) => keep.test(id) && !id.endsWith(':batch')));
const body = `// Generated by scripts/snapshot-prices.ts on ${new Date().toISOString().slice(0, 10)}. USD per token.
import type { Price } from './pricing.ts';

export const SNAPSHOT_DATE = '${new Date().toISOString().slice(0, 10)}';
export const SNAPSHOT: Record<string, Price> = ${JSON.stringify(picked, null, 1)};
`;
writeFileSync(new URL('../src/prices-snapshot.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(picked).length} models`);
